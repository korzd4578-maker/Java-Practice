package Practice02;

public class ex36 {
    public static void main(String[] args) {

        double num = 5.67;
        double negNum = -5.67;

        System.out.println("Math.round(5.67): " + Math.round(num));
        System.out.println("Math.ceil(5.67): " + Math.ceil(num));
        System.out.println("Math.floor(5.67): " + Math.floor(num));

        System.out.println("Math.round(-5.67): " + Math.round(negNum));
        System.out.println("Math.ceil(-5.67): " + Math.ceil(negNum));
        System.out.println("Math.floor(-5.67): " + Math.floor(negNum));

    }
}
