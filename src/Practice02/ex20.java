package Practice02;

public class ex20 {
    public static void main(String[] args) {

        int score = 100;

        score += 50;
        System.out.println("Після додавання: " + score);

        score -= 20;
        System.out.println("Після віднімання: " + score);

        score *= 2;
        System.out.println("Після множення: " + score);

        score /= 4;
        System.out.println("Після ділення: " + score);

    }
}
